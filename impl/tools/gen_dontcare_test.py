#!/usr/bin/env python3
"""Зонд безразличных битов: для каждой формы с u=1/v=1, которой дизассемблер
не даёт имени, исполняем её рядом с базовой формой на ТЕХ ЖЕ операндах и
сравниваем результаты сложением по модулю два.

Если результаты совпадают — бит действительно безразличен, и слово исполняется
как базовая операция. Если нет — за этой кодировкой стоит отдельная инструкция,
и её надо назвать. Ничего не предполагаем: читаем ответ у железа.
"""
MNEMO = ['MOV','LSL','ASR','ROR','AND','ANN','IOR','XOR',
         'ADD','SUB','MUL','DIV','FAD','FSB','FML','FDV']
# op -> (младшее слово операнда b, старшее, младшее c, старшее)
INT = (0xF0F0, 0xF0F0, 0x0005, 0x0000)

# Формы, где бит ЗНАЧИМ: результат отличается от базового. Значения измерены на
# железе и зафиксированы, чтобы изменение поведения не прошло молча.
#   DIV: делитель получает ~u, поэтому u=1 — беззнаковое деление.
#        0xF0F0F0F0 DIV 5 = 0xFCFCFCFC знаково и 0x30303030 беззнаково.
#   FSB: сумматор получает u и v и уходит в режим преобразования целое/плавающее.
#        Архитектурно эти формы не определены — компилятор эмитит FLT и FLOOR
#        только через FAD. Значения заперты как есть, смысл им не приписывается.
DIFFER = {
    (11, 1, 0): (0x30303030, "UDIV: беззнаковое деление"),
    (11, 1, 1): (0x30303030, "UDIV: бит v делителю безразличен"),
    (13, 1, 0): (0x4B3FFFFC, "FSB.u: сумматор в режиме преобразования"),
    (13, 0, 1): (0x00500000, "FSB.v: то же с усечением"),
    (13, 1, 1): (0x00BFFFFC, "FSB.uv"),
}
FP  = (0x0000, 0x3FC0, 0x0000, 0x4010)          # 1.5 и 2.25

def word(u, v, a, b, op, c):
    return ((u << 1 | v) << 28) | (a << 24) | (b << 20) | (op << 16) | c

out = ["; T1.17 — зонд безразличных битов u и v (СГЕНЕРИРОВАН tools/gen_dontcare_test.py).",
       "; Для каждой формы: базовая (u=0,v=0) в R3, испытуемая в R4, XOR в R5.",
       "; R5 = 0 означает, что бит безразличен и слово исполняется как базовая операция.",
       ""]
n = 0
for op in (1, 2, 3, 4, 5, 6, 7, 11, 13, 14, 15):
    lo1, hi1, lo2, hi2 = FP if op >= 12 else INT
    for (u, v) in ((1, 0), (0, 1), (1, 1)):
        if op == 1 and u == 0 and v == 1:
            continue                     # это кодировка CHK, проверяется отдельно
        out += [f"; ── {MNEMO[op]} u={u} v={v} ──",
                # MHI перезаписывает регистр целиком, поэтому старшая половина
                # задаётся первой, а младшая доливается через IOR.
                f"        MHI  R1, 0x{hi1:04X}",
                f"        IOR  R1, R1, 0x{lo1:04X}",
                f"        MHI  R2, 0x{hi2:04X}",
                f"        IOR  R2, R2, 0x{lo2:04X}",
                f"        WORD 0x{word(0,0,3,1,op,2):08X}      ; {MNEMO[op]} R3, R1, R2",
                f"        WORD 0x{word(u,v,4,1,op,2):08X}      ; то же с u={u} v={v}",
                 "        XOR  R5, R3, R4"]
        key = (op, u, v)
        if key in DIFFER:
            val, why = DIFFER[key]
            out += [f"; EXPECT R4 = 0x{val:08X}   ; {why}", ""]
        else:
            out += ["; EXPECT R5 = 0", ""]
        n += 1
out.append("        HALT")
open("tests/t1_dontcare.s","w").write("\n".join(out) + "\n")
print(f"tests/t1_dontcare.s: {n} сравнений")
