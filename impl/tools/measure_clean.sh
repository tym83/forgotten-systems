#!/bin/bash
# ЧЕСТНЫЙ замер динамической цены проверок времени исполнения.
#
# ⚠ Найдено аудитом: двухстадийная схема в measure3.sh повторяла ту самую ошибку,
# от которой защищалась. В стадии 2 каждая конфигурация пересобирала компилятор
# ИЗ СВОЕГО пропатченного ORG.Mod — значит компилятор A не только не содержал
# проверок внутри, но и НЕ ГЕНЕРИРОВАЛ их, то есть делал меньше работы.
# Confound переезжал на стадию позже, а не исчезал.
#
# Здесь стадия 2 собирается из ЭТАЛОННОГО ORG.Mod для всех конфигураций.
# Тогда порождаемый код побитово одинаков, и различается ТОЛЬКО наличие проверок
# внутри самого двоичного кода компилятора. Это и есть цена их исполнения.
set -e
P="$(cd "$(dirname "$0")/.." && pwd)"; NB="$P/ext/norebo"
COMP="ORS.Mod ORB.Mod ORG.Mod ORP.Mod"
LOAD="${*:-Texts.Mod Fonts.Mod Files.Mod Modules.Mod Oberon.Mod}"

# стадия 2: компилятором конфигурации X собрать компилятор ИЗ ЭТАЛОННОГО исходника
# ⚠ Вторая ловушка, в которую я попал при самой починке: NOREBO_PATH обслуживает
# И поиск .rsc (компилятор, которым компилируем), И поиск .Mod (что компилируем).
# Если в путь положить build/cfgX, оттуда возьмётся не только компилятор, но и
# ПРОПАТЧЕННЫЙ ORG.Mod — и порождаемый код снова разойдётся.
# Решение: отдельный каталог только с двоичными модулями конфигурации, без исходников.
# ⚠ Найдено при починке: путь был неверен. Двоичные модули конфигураций лежат
# в build/s2X (их собирает стадия 1 в tools/measure3.sh), а в build/cfgX только
# исходник ORG.Mod. Копирование шло с `|| true`, поэтому отсутствие файлов
# проглатывалось: все три конфигурации оказывались одним и тем же компилятором
# Norebo, «контроль идентичности» тривиально проходил, а разница выходила
# ровно +0.00%. Тот же класс green-on-failure, что вскрыл мутационный аудит.
for cfg in A B E; do
  src="$P/build/s2$cfg"
  if ! ls "$src"/ORP.rsc >/dev/null 2>&1; then
    echo "❌ нет двоичных модулей конфигурации $cfg в $src" >&2
    echo "   сначала: make configs && bash tools/measure3.sh" >&2
    exit 1
  fi
  bin="$P/build/onlyrsc$cfg"; rm -rf "$bin"; mkdir -p "$bin"
  cp "$src"/*.rsc "$bin"/
  # Символьные файлы стадия 1 не перезаписывает (исходники те же), поэтому их
  # там может не быть — берутся из штатного пути Norebo. Отсутствие .smb
  # допустимо, отсутствие .rsc — нет, и проверено выше жёстко.
  if ls "$src"/*.smb >/dev/null 2>&1; then cp "$src"/*.smb "$bin"/; fi
  d="$P/build/clean2$cfg"; rm -rf "$d"; mkdir -p "$d"; cd "$d"
  args=""; for m in $COMP; do args="$args $m/s"; done
  NOREBO_PATH="$d:$bin:$NB/Norebo:$NB/Oberon:$NB/build2" \
    "$NB/norebo.bin" ORP.Compile $args > build.log 2>&1
done

# ⚠ Конфигурация E ставит в свой вывод версию 2 — намеренная блокировка, чтобы
# старый загрузчик (versionkey = 1X в Modules.Mod) не принял код с аппаратной
# CHK. Блокировка работает: без этого шага стадия 2 для E просто НЕ ЗАГРУЖАЛАСЬ,
# прогон давал пустой лог, и `set -e` обрывал скрипт сразу после «нагрузка:».
# Именно это и был симптом «скрипт ничего не выводит». Для замера версия
# возвращается в 1 — на копии в build/, осознанно и только здесь.
python3 "$P/tools/rsc_setversion.py" 1 "$P"/build/clean2E/*.rsc > /dev/null

# Двоичные модули стадии 2 ОБЯЗАНЫ различаться — в этом и смысл: у A проверок внутри
# нет, у B и E есть. А вот код, который они ПОРОЖДАЮТ на нагрузке, обязан совпадать:
# все три собраны из эталонного ORG.Mod и потому эмитят одно и то же.
echo "нагрузка: $LOAD"
for cfg in A B E; do
  d="$P/build/cleanrun$cfg"; rm -rf "$d"; mkdir -p "$d"; cd "$d"
  args=""; for m in $LOAD; do args="$args $m/s"; done
  NOREBO_CYCLES=1 NOREBO_PATH="$P/build/clean2$cfg:$NB/Norebo:$NB/Oberon:$NB/build2" \
    "$NB/norebo.bin" ORP.Compile $args > run.log 2>&1
done

# контроль: порождённый на нагрузке код обязан быть ИДЕНТИЧЕН у всех трёх
echo; echo "контроль: код, порождённый на нагрузке"
ok=1
for f in Texts Fonts Files Modules Oberon; do
  a=$(md5 -q "$P/build/cleanrunA/$f.rsc" 2>/dev/null)
  b=$(md5 -q "$P/build/cleanrunB/$f.rsc" 2>/dev/null)
  e=$(md5 -q "$P/build/cleanrunE/$f.rsc" 2>/dev/null)
  if [ -n "$a" ] && [ "$a" = "$b" ] && [ "$b" = "$e" ]; then printf "  %-9s ✅ идентичен\n" "$f"
  else printf "  %-9s ❌ различается\n" "$f"; ok=0; fi
done
[ $ok -eq 1 ] || { echo; echo "❌ КОНТРОЛЬ НЕ ВЫПОЛНЕН: конфигурации порождают разный код,"
                   echo "   значит разница в тактах включает работу по кодогенерации"; exit 1; }

python3 - "$P/build" <<'PY'
import re, sys, pathlib
b = pathlib.Path(sys.argv[1])
def get(c):
    t = (b / f"cleanrun{c}" / "run.log").read_text(errors="replace")
    m = re.search(r"CYCLES (\d+) INSNS (\d+)", t)
    code = sum(int(x) for x in re.findall(r"^\s+compiling \w+\s+(\d+)", t, re.M))
    return (int(m.group(1)), int(m.group(2)), code)
A, B_, E = get("A"), get("B"), get("E")
print(f"\n{'конфигурация':<24}{'такты':>14}{'инструкции':>14}{'код':>8}")
print("-"*62)
for n, v in (("A — нет проверок", A), ("B — программные", B_), ("E — аппаратные", E)):
    print(f"{n:<24}{v[0]:>14,}{v[1]:>14,}{v[2]:>8,}")
print("-"*62)
print(f"\nЧЕСТНАЯ цена проверок (порождаемый код одинаков):")
print(f"  программные  такты +{100*(B_[0]-A[0])/A[0]:.2f}%   инстр. +{100*(B_[1]-A[1])/A[1]:.2f}%")
print(f"  аппаратные   такты +{100*(E[0]-A[0])/A[0]:.2f}%   инстр. +{100*(E[1]-A[1])/A[1]:.2f}%")
# ⚠ Если конфигурации дали одинаковые числа, делить не на что: это не результат
# «цена ноль», а признак того, что сравнивались три копии одного компилятора.
if B_[0] == A[0] and E[0] == A[0]:
    print("\n❌ все три конфигурации дали ОДИНАКОВЫЕ числа — значит сравнивался")
    print("   один и тот же двоичный код. Замер недействителен.")
    sys.exit(1)
print(f"\n  аппаратура снимает {100*(B_[0]-E[0])/(B_[0]-A[0]):.1f}% цены проверок")
PY
