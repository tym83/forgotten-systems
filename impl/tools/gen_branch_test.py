#!/usr/bin/env python3
"""Генерирует проверку ВСЕХ 16 условий ветвления на четырёх состояниях флагов.

Ожидаемый исход берётся из таблицы истинности спецификации, а не из наблюдения,
поэтому тест ловит расхождение железа со спецификацией, а не подгоняется под него.
Состояния флагов предварительно ИЗМЕРЕНЫ (tests/t1_probe_flags.s).
"""
COND = [("MI",0),("EQ",1),("CS",2),("VS",3),("LS",4),("LT",5),("LE",6),("",7),
        ("PL",8),("NE",9),("CC",10),("VC",11),("HI",12),("GE",13),("GT",14),("NV",15)]

def taken(cc, N, Z, C, V):
    S = N ^ V
    base = [N, Z, C, V, C or Z, S, S or Z, 1][cc & 7]
    return bool(base) ^ bool(cc & 8)

# Состояния флагов. 🔴 Найдено аудитом: в первой версии во ВСЕХ четырёх было V=0,
# из-за чего на этом наборе неразличимы пять условий из восьми:
#   V ≡ 0     -> VS не срабатывает никогда, VC всегда
#   S = N^V ≡ N -> LT/GE неотличимы от MI/PL
#   S|Z ≡ C|Z -> LE/GT неотличимы от LS/HI
# Мутации «VS/VC мертво», «S = N», «LS ≡ LE», «MI ≡ LT» проходили как зелёные.
# Добавлены состояния с V=1 и с N=1,Z=0,C=0, чтобы все восемь функций различались.
#
# (комментарий, код установки, N, Z, C, V)
STATES = [
    ("S1: 5-5=0",        "        SUB  R3, R1, R1\n", 0,1,0,0),
    ("S2: 0-5 заём",     "        SUB  R3, R0, R1\n", 1,0,1,0),
    ("S3: 7-5=2",        "        SUB  R3, R2, R1\n", 0,0,0,0),
    ("S4: -1+1 перенос", "        ADD  R3, R4, 1\n",  0,1,1,0),
    # переполнение знака: 0x7FFFFFFF + 1 -> N=1, V=1, C=0
    ("S5: max+1 перепол.", "        ADD  R3, R6, 1\n", 1,0,0,1),
    # обратное переполнение: 0x80000000 - 1 -> N=0, V=1, C=0
    ("S6: min-1 перепол.", "        SUB  R3, R7, 1\n", 0,0,0,1),
    # N=1 без переноса и без переполнения. ВАЖНО: IOR здесь не годится — логические
    # операции в RISC5 не трогают C и V (RISC5.v: cx/vv меняются только на ADD/SUB),
    # и флаги протекли бы из предыдущего состояния. Нужен ADD.
    ("S7: N=1,C=0,V=0",  "        ADD  R3, R7, 0\n",   1,0,0,0),
]

out = ["""; T1.6 — ВСЕ 16 условий ветвления на четырёх состояниях флагов.
; Ожидаемый исход вычислен по таблице истинности из спецификации:
;   MI=N  EQ=Z  CS=C  VS=V  LS=C|Z  LT=N^V  LE=(N^V)|Z  T=1
;   старший бит условия инвертирует результат (PL, NE, CC, VC, HI, GE, GT, F)
; Состояния флагов предварительно измерены (t1_probe_flags.s).
; Схема проверки: R5 := 0 ; <установка флагов> ; B<cond> skip ; R5 := 1 ; skip:
;   Обнуление R5 идёт ПЕРВЫМ: запись в регистр сама ставит N и Z.
;   R5 = 0 -> переход СОСТОЯЛСЯ, R5 = 1 -> НЕ состоялся.
        MOV  R0, 0
        MOV  R1, 5
        MOV  R2, 7
        MOV  R4, -1
        MOV  R6, 0
        MHI  R6, 0x7FFF
        IOR  R6, R6, 0xFFFF      ; R6 = 0x7FFFFFFF, максимум со знаком
        MOV  R7, 0
        MHI  R7, 0x8000          ; R7 = 0x80000000, минимум со знаком
"""]
n = 0
for name, setup, N, Z, C, V in STATES:
    out.append(f"; ──────── {name}  (N={N} Z={Z} C={C} V={V}) ────────\n")
    for cc_name, cc in COND:
        # ВАЖНО: MOV R5,0 обнуляет регистр и тем самым СТАВИТ N=0, Z=1
        # (флаги ставятся при ЛЮБОЙ записи в регистр — см. FINDING в t1_flags).
        # Поэтому обнуление идёт ДО установки флагов, а не после.
        out.append("        MOV  R5, 0\n")
        out.append(setup)                       # устанавливаем проверяемые флаги
        out.append(f"        B{cc_name} sk{n}\n")
        out.append("        MOV  R5, 1\n")
        out.append(f"sk{n}:\n")
        exp = 0 if taken(cc, N, Z, C, V) else 1
        lbl = cc_name if cc_name else "T"
        out.append(f"; EXPECT R5 = {exp}   ; {lbl} при N={N} Z={Z} C={C} V={V}\n")
        n += 1
out.append("        HALT\n")
open("tests/t1_branch.s","w").write("".join(out))
print(f"tests/t1_branch.s: {n} проверок условий")
