; T1.5 — память: слово и байт, отрицательные смещения, выбор байтовой полосы.
        MOV  R0, 0
        MOV  R1, 0
        MHI  R1, 0x1234
        IOR  R1, R1, 0x5678      ; R1 = 0x12345678
        MOV  R2, 0x100           ; база
; --- слово
        ST   R1, R2, 0
        LD   R3, R2, 0
; EXPECT R3 = 305419896
; --- отрицательное смещение (20-битное поле со знаком)
        ST   R1, R2, -4
        LD   R3, R2, -4
; EXPECT R3 = 305419896
; --- байтовая запись выбирает полосу по двум младшим битам адреса
        MOV  R4, 0
        ST   R4, R2, 16          ; обнулили слово
        MOV  R5, 0xAB
        STB  R5, R2, 16          ; байт 0
        LD   R6, R2, 16
; EXPECT R6 = 171                ; 0x000000AB
        STB  R5, R2, 17          ; байт 1
        LD   R6, R2, 16
; EXPECT R6 = 43947              ; 0x0000ABAB
        STB  R5, R2, 18
        STB  R5, R2, 19
        LD   R6, R2, 16
; EXPECT R6 = 2880154539         ; 0xABABABAB
; --- байтовое чтение выбирает ту же полосу
        ST   R1, R2, 32          ; 0x12345678
        LDB  R7, R2, 32
; EXPECT R7 = 120                ; 0x78
        LDB  R7, R2, 33
; EXPECT R7 = 86                 ; 0x56
        LDB  R7, R2, 34
; EXPECT R7 = 52                 ; 0x34
        LDB  R7, R2, 35
; EXPECT R7 = 18                 ; 0x12
        HALT
