; T1.7 — прерывания. Эталонный эмулятор их не моделирует вообще (ни SPC, ни RTI,
; ни irq), поэтому golden-модели нет и сверять можно только с RTL.
;
; Проверяется: вход по вектору 0x00000004, сохранение и восстановление флагов через
; SPC, возврат по RTI ровно на прерванное место, взведение и снятие режима обработчика,
; и — отдельно — что регистр H НЕ сохраняется (задокументированное поведение,
; из-за которого MUL/DIV в обработчике небезопасны).
;
; Кодирование STI/CLI требует условия NV («никогда»): побочный эффект в RISC5.v:181
; от условия не зависит, а при «всегда» инструкция выполнила бы переход по регистру.
        MOV  R0, 0
; ── вектор по адресу 4: переход на handler (F3 offset, cond=7)
        MOV  R1, 0
        MHI  R1, 0xE700
        MOV  R2, 0
        MHI  R2, 0x00FF
        IOR  R2, R2, 0xE060      ; адрес handler
        SUB  R3, R2, 4
        ASR  R3, R3, 2
        SUB  R3, R3, 1
        ADD  R1, R1, R3
        ST   R1, R0, 4
; ── готовим адрес запроса прерывания и значение
        MOV  R7, 0
        MHI  R7, 0x00FF
        IOR  R7, R7, 0xFFC0
        MOV  R8, 1
; ── H перед прерыванием
        MOV  R4, 5
        MUL  R5, R4, R4          ; H := 0
; ── разрешаем прерывания
        STI
; EXPECT IE = 1
; ── ставим ОТЛИЧИТЕЛЬНОЕ состояние флагов ПЕРЕД запросом:
;    ST флаги не трогает, значит в момент прерывания будет именно это состояние
        SUB  R6, R0, R4          ; N=1, Z=0
        ST   R8, R7, 0           ; запрос прерывания; флаги не меняет
; ── сюда управление вернётся после RTI.
;    Проверки стоят ДО первой инструкции возврата: любая запись в регистр
;    сама ставит N и Z и затёрла бы восстановленное состояние.
; EXPECT N = 1               ; флаг восстановлен из SPC
; EXPECT Z = 0
; EXPECT IMD = 0             ; режим обработчика снят
; EXPECT R11 = 13107         ; обработчик отработал
; EXPECT H = 1                ; H НЕ восстановлен: оставлен обработчиком
        MOV  R9, 0x1111
        MOV  R10, 0x2222
        HALT
        WORD 0
; ── обработчик, слово 24 = адрес 0x00FFE060
handler:
        MOV  R11, 0x3333
; H перед прерыванием был 0 (5*5 не переполняет). Портим его так, чтобы
; старшие биты стали ненулевыми: 0x10000 * 0x10000 = 0x1_0000_0000 -> H = 1.
        MOV  R14, 0
        MHI  R14, 0x0001
        MUL  R13, R14, R14       ; H := 1
        RTI
