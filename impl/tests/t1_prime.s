; T1.18 — первая инструкция программы обязана исполняться.
; RISC5 — машина с предвыборкой: на шине адреса стоит PC+1, а исполняется то,
; что лежит в регистре команд. Если после сброса IR не заполнить, первый такт
; исполнит мусор, а первое слово программы машина не прочитает вовсе.
; Ошибка пряталась во всех 264 проверках: каждая начиналась с инструкции,
; потеря которой безразлична. Нашлась зондом делителя — `MOV R1, 100` терялся,
; и деление давало ноль.
        MOV  R5, 42
        MOV  R6, 7
; EXPECT R5 = 42
; EXPECT R6 = 7
        HALT
