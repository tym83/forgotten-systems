; Что на самом деле делает UMUL в RISC5.
; Multiplier.v: w1 = (S==32) & u ? {P[63],P[63:32]} - {w0[31],w0}
;                                : {P[63],P[63:32]} + {w0[31],w0}
; Слагаемое {w0[31], w0} расширяется ЗНАКОМ ВСЕГДА, независимо от u.
; Флаг u (= ~u инструкции) управляет только последним шагом, то есть знаком x.
; Следствие: UMUL считает x БЕЗЗНАКОВО, а y ЗНАКОВО — смешанное умножение.
;
; В формате F0: UMUL a, b, c  ->  x = R[b], y = R[c].
; Значит знаковым трактуется ВТОРОЙ операнд.
        MOV  R0, 0
        MOV  R1, -1              ; 0xFFFFFFFF
        MOV  R2, 2
; --- случай, различающий модели: x = 2 (мал), y = 0xFFFFFFFF
;     истинно беззнаково: 2 * 4294967295 = 0x1_FFFFFFFE -> H = 1
;     смешанно (y знаково = -1): 2 * -1 = 0xFFFFFFFF_FFFFFFFE -> H = 0xFFFFFFFF
        UMUL R3, R2, R1
; EXPECT R3 = 4294967294
; EXPECT H = 4294967295
; --- обратный порядок: x = 0xFFFFFFFF (беззнаково), y = 2 (положительно)
;     обе модели совпадают: 4294967295 * 2 = 0x1_FFFFFFFE -> H = 1
        UMUL R4, R1, R2
; EXPECT R4 = 4294967294
; EXPECT H = 1
; --- знаковое MUL для контраста: (-1) * 2 = -2
        MUL  R5, R1, R2
; EXPECT R5 = 4294967294
; EXPECT H = 4294967295
        HALT
