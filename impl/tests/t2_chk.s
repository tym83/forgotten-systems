; T2-CHK — аппаратная проверка границ массива, ПРИНЯТОЕ кодирование.
;
; F0 (p=0,q=0) | v=1 | op=1 (алиас LSL) | индекс в поле b |
; предел в IR[15:8] (8 бит) | номер ловушки 1 в IR[7:4] | c=12 (MT)
;
; Предел 8 бит, а не 12, выбран по данным: медианный массив в системе — 32 элемента,
; а 12-битный вариант перекрывает биты номера ловушки и заставляет систему сообщать
; НЕ ТУ ошибку (измерено: выход за границу массива объявлялся разыменованием NIL).
; См. docs/FINDING-08-encoding-decision.md
;
; Семантика при срабатывании — ровно как у BLR: R15 := PC+4 ; PC := R[12].
; Не срабатывает — не пишет ни регистра, ни флагов.
        MOV  R0, 0
; R12 = MT = адрес обработчика ловушек (метка handler ниже, 0x00FFE05C)
        MOV  R12, 0
        MHI  R12, 0x00FF
        IOR  R12, R12, 0xE05C
; --- портим флаги, чтобы проверить: не сработавшая CHK их не трогает
        MOV  R1, 5
        SUB  R2, R0, R1            ; N=1, Z=0
; --- индекс 5 < предел 10: не срабатывает
        CHKS R1, 10
; EXPECT N = 1
; EXPECT Z = 0
; EXPECT CYCLES = 1
; --- индекс на границе: 10 >= 10 — должна сработать
        MOV  R3, 10
        CHKS R3, 10
; сюда управление уже не вернётся
        MOV  R4, 0x1111            ; НЕ должна выполниться
        HALT
; выравнивание: handler должен попасть на слово 23 = байт 0x5C
        WORD 0
        WORD 0
        WORD 0
        WORD 0
        WORD 0
        WORD 0
        WORD 0
        WORD 0
        WORD 0
        WORD 0
        WORD 0
        WORD 0
handler:
        MOV  R5, 0x2222            ; признак, что обработчик получил управление
; EXPECT R5 = 8738
; EXPECT R4 = 0
        HALT
