; Надбавка за подряд идущие FP-операции.
; ПРАВИЛО (выведено измерением): стоимость подряд идущей операции равна
; ПЕРИОДУ СЧЁТЧИКА, то есть 2^(его разрядность), а не длине операции.
; На такте ретайра run ещё высок, поэтому S не обнуляется, а уходит за конец
; и следующая операция вынуждена докрутить счётчик до переполнения.
;   FPAdder      State 2 бита -> период  4, операция  4 шага -> надбавки НЕТ
;   FPMultiplier S     5 бит  -> период 32, операция 26 шагов -> 26 => 32  (+23%)
;   FPDivider    S     5 бит  -> период 32, операция 27 шагов -> 27 => 32  (+19%)
;   Multiplier   S     6 бит  -> период 64, операция 34 шага  -> 34 => 64  (+88%)
;   Divider      S     6 бит  -> период 64, операция 34 шага  -> 34 => 64  (+88%)
; Разрыв любой не-арифметической инструкцией сбрасывает счётчик и возвращает цену.
        MOV  R7, 0
        MHI  R7, 0x3F80        ; 1.0
        MOV  R8, 0
        MHI  R8, 0x4000        ; 2.0
; --- умножение после НЕ-FP инструкции: счётчик сброшен
        ADD  R0, R0, 0
        FML  R9, R7, R8
; EXPECT CYCLES = 26
; --- подряд: платим остаток переполнения счётчика
        FML  R10, R7, R8
; EXPECT CYCLES = 32
        FML  R11, R7, R8
; EXPECT CYCLES = 32
; --- разрываем одной дешёвой инструкцией: снова 26
        ADD  R0, R0, 0
        FML  R12, R7, R8
; EXPECT CYCLES = 26
; --- сумматор: подряд НЕ дорожает
        FAD  R13, R7, R8
; EXPECT CYCLES = 4
        FAD  R14, R7, R8
; EXPECT CYCLES = 4
; --- делитель: период 27 при том же 5-битном счётчике
        ADD  R0, R0, 0
        FDV  R1, R8, R7
; EXPECT CYCLES = 27
        FDV  R2, R8, R7
; EXPECT CYCLES = 32
; --- целые MUL: счётчик 6 БИТ -> период 64, а операция 34 шага
        ADD  R0, R0, 0
        MUL  R3, R7, R8
; EXPECT CYCLES = 34
        MUL  R4, R7, R8
; EXPECT CYCLES = 64
        MUL  R5, R7, R8
; EXPECT CYCLES = 64
        ADD  R0, R0, 0
        DIV  R6, R8, R7
; EXPECT CYCLES = 34
        DIV  R1, R8, R7
; EXPECT CYCLES = 64
        HALT
