; Проба для сверки QEMU с настоящим RTL.
; Каждая команда выбрана так, чтобы задеть разные части АЛУ и флаги.
        MOV R1, 100
        MOV R2, 7
        ADD R3, R1, R2          ; 107
        SUB R4, R1, R2          ; 93
        AND R5, R1, R2          ; 100 & 7 = 4
        IOR R6, R1, R2          ; 103
        XOR R7, R1, R2          ; 99
        LSL R8, R2, 3           ; 56
        ASR R9, R1, 2           ; 25
        MUL R10, R1, R2         ; 700
        MOV R11, -1
        ADD R12, R11, 1         ; 0, перенос
        SUB R13, R2, R1         ; -93, знак
loop:   B loop
